# -------------------------------------------------------------------------
# 3. 마스터 프롬프트 템플릿 (수정된 버전)
# (모델이 헷갈리지 않도록 변수를 줄이고 지시를 더 명확하게 변경)
# -------------------------------------------------------------------------
def create_master_prompt(stage_info, perpetrator, victim):
    # KoAlpaca의 Instruction 형식에 맞춘 프롬프트
    return f"""###_Instruction_Statement:
다음은 'User A'와 'User B'가 10턴(turn) 동안 대화하는 스크립트를 생성하는 임무입니다.

### 역할 ###
* **User A (가해자):** {perpetrator}
* **User B (피해자):** {victim}

### 상황 ###
* **임무:** User A는 {stage_info['stage']} 단계의 목표를 달성해야 합니다.
* **User A의 목표:** {stage_info['goal']}
* **User B의 반응:** {victim}의 특성을 가진 인물로 반응합니다.

### 요구 사항 ###
1. User A와 User B가 번갈아 가며 총 10턴의 대화를 생성합니다.
2. User A는 자신의 목표를 달성하기 위해 점진적으로 대화를 이끌어 갑니다.
3. 대화는 반드시 자연스러운 구어체여야 합니다.

### 출력 형식 ###
User A: [대화 내용]
User B: [대화 내용]
(총 10턴 반복)

이제 위 시나리오에 맞는 대화 스크립트 생성을 시작합니다.

###_Response_:
"""


# -------------------------------------------------------------------------
# 4. 메인 실행 루프 (1000회 자동 생성)
# -------------------------------------------------------------------------
print(f"\n총 {TOTAL_DATASETS_TO_GENERATE}개의 데이터셋 생성을 시작합니다...")

for i in range(TOTAL_DATASETS_TO_GENERATE):
    print(f"\n--- [ {i + 1} / {TOTAL_DATASETS_TO_GENERATE} ] 번째 데이터 생성 중 ---")

    # 변수 리스트에서 무작위로 하나씩 선택
    selected_stage = random.choice(stage_list)
    selected_perpetrator = random.choice(perpetrator_list)
    selected_victim = random.choice(victim_list)

    # 선택된 변수로 마스터 프롬프트 생성
    user_prompt = create_master_prompt(
        selected_stage,
        selected_perpetrator,
        selected_victim
    )

    # 3-2. 모델 입력 생성 (토크나이징)
    inputs = tokenizer(user_prompt, return_tensors="pt").to(device)

    # ------------------------------------------------------------------
    # [수정 2] (필수) 'token_type_ids' 오류 해결을 위해 추가된 코드
    # ------------------------------------------------------------------
    # KoAlpaca (GPT 계열) 모델은 token_type_ids를 사용하지 않으므로,
    # 토크나이저가 생성했더라도 inputs 딕셔너리에서 삭제합니다.
    if 'token_type_ids' in inputs:
        del inputs['token_type_ids']
    # ------------------------------------------------------------------

    # 3-3. 모델 출력 생성 (추론)
    try:
        outputs = model.generate(
            **inputs,
            max_new_tokens=1024,  # 10턴의 대화는 길 수 있으므로 넉넉하게 설정
            eos_token_id=2,
            do_sample=True,
            temperature=0.7,
            top_p=0.9
        )

        # 3-4. 출력 결과 디코딩 (프롬프트 부분 제외)
        result_text = tokenizer.decode(
            outputs[0][inputs['input_ids'].shape[1]:],
            skip_special_tokens=True
        ).strip()

        # 3-5. 결과 파일 저장
        output_filename = os.path.join(OUTPUT_DIR, f"scenario_{i + 1}.txt")

        with open(output_filename, "w", encoding="utf-8") as f:
            f.write("### 원본 생성 프롬프트 ###\n")
            f.write(user_prompt.replace("###_Response_:", "").strip())  # 원본 프롬프트(시나리오) 저장
            f.write("\n\n### KoAlpaca 생성 결과 ###\n")
            f.write(result_text)  # 모델이 생성한 대화 내용 저장

        print(f"-> [ {output_filename} ] 파일에 성공적으로 저장되었습니다.")

    except torch.cuda.OutOfMemoryError:
        print("[오류] GPU 메모리 부족 (Out of Memory)! 생성 중단.")
        break  # 메모리 부족 시 루프 중단
    except Exception as e:
        print(f"[오류] 알 수 없는 오류 발생: {e}")

print(f"\n총 {i + 1}개의 데이터셋 생성을 완료했습니다.")