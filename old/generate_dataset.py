# -------------------------------------------------------------------------
# 3. 마스터 프롬프트 템플릿 (Base 모델용 "Few-Shot" 방식)
# -------------------------------------------------------------------------
def create_master_prompt(stage_info, perpetrator, victim):
    # Base 모델이 패턴을 학습하도록 가짜 예시를 제공합니다.
    few_shot_example = """
시나리오:
- User A (가해자): 20대 남성, '포토그래퍼' 사칭
- User B (피해자): 15세 여성, '모델 지망생'
- 단계: 1단계 (신뢰 구축)
- 목표: 피해자와 친밀감을 쌓고, '특별한 사진'을 찍어주겠다며 다음 연락을 유도한다.

대화:
User A: 안녕하세요, 인스타 피드 잘 보고 있어요. 사진 모델에 관심 있으신가요?
User B: 헉 안녕하세요? 네! 관심은 있는데... 제가 잘 할 수 있을지..
User A: 그럼요. 지민님(가명)은 눈빛이 정말 좋아요. 제가 무료로 프로필 사진 몇 장 찍어드리고 싶은데.
User B: 정말요? 그래도 돼요?
User A: 물론이죠. 대신 조건이 있어요.
User B: 조건이요?
User A: 네. 제가 찍어주는 사진은 다른 데 공개하면 안 돼요. 우리 둘만 보는 거예요.
User B: 아... 네! 알겠어요!
User A: 좋아요. 그럼 우리 따로 편하게 연락할까요? 카톡 아이디 알려줄 수 있어요?
User B: 네! 제 아이디는 [ID] 예요!
"""

    # 이제 실제 생성할 프롬프트를 만듭니다.
    actual_prompt = f"""
시나리오:
- User A (가해자): {perpetrator}
- User B (피해자): {victim}
- 단계: {stage_info['stage']}
- 목표: {stage_info['goal']}

대화:
User A: """

    return f"<|begin_of_text|>{few_shot_example}{actual_prompt}"


# -------------------------------------------------------------------------
# 4. 메인 실행 루프 (Base 모델용)
# -------------------------------------------------------------------------
print(f"\n총 {TOTAL_DATASETS_TO_GENERATE}개의 데이터셋 생성을 시작합니다...")

# Llama 3의 종료 토큰 ID 리스트
terminators = [
    tokenizer.eos_token_id,
    tokenizer.convert_tokens_to_ids("<|eot_id|>")
]

for i in range(TOTAL_DATASETS_TO_GENERATE):
    print(f"\n--- [ {i + 1} / {TOTAL_DATASETS_TO_GENERATE} ] 번째 데이터 생성 중 ---")

    # 변수 리스트에서 무작위로 하나씩 선택
    selected_stage = random.choice(stage_list)
    selected_perpetrator = random.choice(perpetrator_list)
    selected_victim = random.choice(victim_list)

    # 선택된 변수로 마스터 프롬프트 생성
    user_prompt = create_master_prompt(
        selected_stage,
        selected_perpetrator,
        selected_victim
    )

    # 3-2. 모델 입력 생성 (토크나이징)
    inputs = tokenizer(user_prompt, return_tensors="pt").to(device)

    # 3-3. 모델 출력 생성 (추론)
    try:
        # [수정됨] "무한 루프" 오류를 해결하기 위해 반복 방지 옵션 2개 추가
        outputs = model.generate(
            **inputs,
            max_new_tokens=1024,
            eos_token_id=terminators,
            do_sample=True,
            temperature=0.7,
            top_p=0.9,
            repetition_penalty=1.15,  # <-- [수정] 동일 단어 반복 방지
            no_repeat_ngram_size=3  # <-- [수정] 3단어 이상 동일 구문 반복 방지
        )

        # 3-4. 출력 결과 디코딩 (프롬프트 부분 제외)
        generated_text_only = tokenizer.decode(
            outputs[0][inputs['input_ids'].shape[1]:],
            skip_special_tokens=True
        ).strip()

        # 'User A: ' + (모델이 생성한 나머지 텍스트)
        result_text = "User A: " + generated_text_only

        # Base 모델이 멈추지 않고 예시 프롬프트까지 뱉는 경우가 있어, 잘라냅니다.
        if "시나리오:" in result_text:
            result_text = result_text.split("시나리오:")[0]

        # 3-5. 결과 파일 저장
        output_filename = os.path.join(OUTPUT_DIR, f"scenario_{i + 1}.txt")

        with open(output_filename, "w", encoding="utf-8") as f:
            f.write("### 원본 생성 프롬프트 ###\n")
            f.write(user_prompt.split("대화:\nUser A: ")[0].strip())
            f.write("\n\n### Llama-3.1-Base 생성 결과 ###\n")
            f.write(result_text)

        print(f"-> [ {output_filename} ] 파일에 성공적으로 저장되었습니다.")

    except torch.cuda.OutOfMemoryError:
        print("[오류] GPU 메모리 부족 (Out of Memory)! 생성 중단.")
        break
    except Exception as e:
        print(f"[오류] 알 수 없는 오류 발생: {e}")

print(f"\n총 {i + 1}개의 데이터셋 생성을 완료했습니다.")